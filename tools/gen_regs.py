"""Generate sw/app/t2t_regs.h from the HLS driver header xt2t_core_hw.h (SPEC 6.7).

    python tools/gen_regs.py [hls/ip/drivers/t2t_core_v1_0/src/xt2t_core_hw.h]

The logical register names of SPEC 6.7 are authoritative; offsets come from HLS.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT = ROOT / "hls" / "ip" / "drivers" / "t2t_core_v1_0" / "src" / "xt2t_core_hw.h"
OUT = ROOT / "sw" / "app" / "t2t_regs.h"


def main(argv=None) -> int:
    src = Path(argv[0]) if argv else DEFAULT
    text = src.read_text()
    regs = re.findall(r"#define XT2T_CORE_CTRL_ADDR_([A-Z0-9_]+)_DATA\s+(0x[0-9a-fA-F]+)", text)
    if not regs:
        raise SystemExit(f"no registers found in {src}")
    names = {n for n, _ in regs}
    needed = {"CTRL", "STATUS", "CLIP_QTY", "MAX_ORDER_QTY", "MAX_POS", "COLLAR", "MIN_GAP_NS",
              "MAX_ORDERS", "LOCKOUT_MS", "MSGS_IN", "ORDERS_OUT", "LAST_SEQ", "ERR_FRAMING"} | \
        {f"POS{i}" for i in range(8)}
    if needed - names:
        raise SystemExit(f"{src.name} lacks registers {sorted(needed - names)}: re-export the IP (make hls)")
    offs = {n: int(o, 16) for n, o in regs}
    if any(offs[f"POS{i}"] != offs["POS0"] + 8 * i for i in range(8)):
        raise SystemExit("POS registers are not contiguous (T2T_REG_POS(p) would be wrong)")
    lines = [
        "// t2t_regs.h -- AXI-Lite register offsets of t2t_core (GENERATED by tools/gen_regs.py",
        f"// from {src.name}; do not edit).  Logical names follow SPEC 6.7.",
        "#ifndef T2T_REGS_H",
        "#define T2T_REGS_H",
        "",
    ]
    for name, off in regs:
        lines.append(f"#define T2T_REG_{name:<18} 0x{int(off, 16):03X}u")
    pos = [n for n, _ in regs if re.fullmatch(r"POS\d", n)]
    lines += ["", f"#define T2T_N_POS_REGS {len(pos)}",
              "#define T2T_REG_POS(p) (T2T_REG_POS0 + 8u * (unsigned)(p))",
              "", "#define T2T_CTRL_STRAT_EN   0x1u", "#define T2T_CTRL_KILL       0x2u",
              "#define T2T_CTRL_DBG_EN     0x4u", "#define T2T_CTRL_SOFT_RESET 0x8u",
              "#define T2T_STATUS_BUSY     0x1u", "", "#endif", ""]
    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT} ({len(regs)} registers)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
